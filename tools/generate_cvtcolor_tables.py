"""Generate FlagCV cvtColor coefficient data from a pinned contrib and OpenCV build."""

import argparse
from hashlib import sha256
from pathlib import Path
import subprocess
from tempfile import TemporaryDirectory


COMMIT = "2f5682ba"
OPENCV = "40738fb16ceddb5fb3fea747585f7ce6abb0605b"


def source(contrib, name):
    return subprocess.check_output(
        ["git", "-C", str(contrib), "show", f"{COMMIT}:modules/triton/src/runtime/{name}"],
        text=True,
    )


def between(text, marker, end):
    i = text.index(marker)
    return text[i:text.index(end, i)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("contrib", type=Path)
    parser.add_argument("opencv_source", type=Path)
    parser.add_argument("opencv_install", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--cxx", default="c++")
    args = parser.parse_args()
    cpu_id = subprocess.check_output(
        ["git", "-C", str(args.opencv_source), "rev-parse", "HEAD"], text=True).strip()
    if cpu_id != OPENCV:
        raise SystemExit(f"expected OpenCV {OPENCV}, found {cpu_id}")
    header = source(args.contrib, "cvtcolor.hpp")
    code = source(args.contrib, "cvtcolor.cpp")
    spec = between(header, "enum class Op", "// The table.")
    arrays = between(header, "struct LabLuvTables", "// Built on first use")
    supported = between(code, "const CodeSpec TABLE[] = {", "\n};") + "\n};"
    generation = between(code, "namespace\n{\n\nconst int kLabShift", "std::string signature(")
    source_code = rf"""#include <opencv2/core.hpp>
#include <opencv2/core/softfloat.hpp>
#include <algorithm>
#include <array>
#include <cmath>
#include <fstream>
#include <iostream>
#include <string>
#include <vector>

{spec}
{arrays}
{supported}
{generation}

template<class Value>
void write(std::ofstream& output, const std::vector<Value>& values) {{
    output.write(reinterpret_cast<const char*>(values.data()), values.size() * sizeof(Value));
}}

int main(int argc, char** argv) {{
    static_assert(sizeof(int) == 4 && sizeof(short) == 2 && sizeof(long long) == 8);
    if (argc != 2) return 1;
    const std::string dir = argv[1];
    std::ofstream row(dir + "/cvtcolor_codes.inc");
    row << "// Generated by tools/generate_cvtcolor_tables.py.\n";
    for (auto c : TABLE) {{
        if (c.op == Op::Xyz || c.op == Op::Lab || c.op == Op::Luv)
            coeffs_for(c.code, c.k);
        row << "{{" << '"' << c.name << '"' << ", " << c.code << ", static_cast<Op>(" << int(c.op)
            << "), " << c.scn << ", " << c.dcn << ", " << c.blue << ", " << c.inverse
            << ", " << c.hrange << ", {{" << c.perm[0] << ", " << c.perm[1] << ", "
            << c.perm[2] << ", " << c.perm[3] << "}}, " << c.gb << ", " << c.swg
            << ", " << c.srgb << ", {{";
        for (int i = 0; i < 9; ++i) {{
            if (i) row << ", ";
            row << c.k[i];
        }}
        row << "}}, " << c.ord << "}},\n";
    }}
    const auto& tab = labluv_tables();
    std::ofstream lab(dir + "/lab-luv-reverse.bin", std::ios::binary);
    write(lab, tab.gamma);
    write(lab, tab.cbrt);
    write(lab, tab.yf);
    write(lab, tab.abxz);
    write(lab, tab.invgamma);
    write(lab, tab.lu);
    write(lab, tab.lv);
    write(lab, tab.lvpl);
    std::ofstream luv(dir + "/luv-forward.bin", std::ios::binary);
    write(luv, tab.luvLut);
    return !row || !lab || !luv;
}}
"""
    # The target package remains independent of OpenCV. This local generation
    # step links the exact softfloat implementation from the pinned CPU build.
    include = args.opencv_install.resolve() / "include/opencv5"
    library = args.opencv_install.resolve() / "lib"
    args.output.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory(prefix="flagcv-cvtcolor-") as temporary:
        root = Path(temporary)
        cpp = root / "generate.cpp"
        exe = root / "generate"
        cpp.write_text(source_code)
        subprocess.run(
            [args.cxx, "-std=c++17", "-O2", "-ffp-contract=off", f"-I{include}", str(cpp),
             f"-L{library}", f"-Wl,-rpath,{library}", "-lopencv_core", "-o", str(exe)],
            check=True,
        )
        subprocess.run([str(exe), str(args.output.resolve())], check=True)

    for name in ("cvtcolor_codes.inc", "lab-luv-reverse.bin", "luv-forward.bin"):
        data = (args.output / name).read_bytes()
        print(f"{sha256(data).hexdigest()} {len(data)} {name}")


if __name__ == "__main__":
    main()
